import SwiftUI

extension View {
    /// Форма в листе над панелью кнопок. Сгруппированная форма держит внизу содержимого отступ 20 pt,
    /// видимый только в конце прокрутки — в середине строки упирались бы прямо в кнопки.
    /// Обрезаем ровно эту полосу: при любой прокрутке до кнопок остаются те же 20 pt.
    func clippedAboveSheetFooter() -> some View {
        mask { Rectangle().padding(.bottom, 20) }
    }
}
